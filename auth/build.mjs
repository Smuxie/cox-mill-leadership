import {readFile, writeFile} from 'node:fs/promises';
const upstream = await readFile(new URL('./src/upstream.js', import.meta.url), 'utf8');
const wrapper = await readFile(new URL('./src/index.js', import.meta.url), 'utf8');
if (!upstream.includes('export default {') || !wrapper.startsWith("import upstream from './upstream.js';")) throw new Error('Authenticator source changed; review the bundling script.');
const bundle = '// Generated by node auth/build.mjs. Upstream MIT license: auth/LICENSE.txt\n' + upstream.replace('export default {','const upstream = {') + '\n' + wrapper.replace("import upstream from './upstream.js';",'');
await writeFile(new URL('./worker.js', import.meta.url), bundle);
console.log('Built auth/worker.js for the Cloudflare dashboard. It contains no credentials.');
